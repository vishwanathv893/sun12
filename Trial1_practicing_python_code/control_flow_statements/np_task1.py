print("Checking whether the given number is negative or zero or positive :-")
x = input("Enter the number :")
x1 = int(x)
if x1<0 :
    print("The entered number is negative.")
elif x1>0 :
    print("The entered number is positive.")
else:
    print("The entered number is zero.")   

   
    
     
    
